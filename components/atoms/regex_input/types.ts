import { StyleProp, TextInputProps, TextStyle } from "react-native";

/****************************************************************************
* RegexInputCheckType: Các loại kiểm tra regex                              *
*****************************************************************************/
export type RegexInputCheckType =
    'length'        /* Kiểm tra độ dài */
    | 'upper'       /* Kiểm tra ký tự in hoa */
    | 'lower'       /* Kiểm tra ký tự in thường */
    | 'digit'       /* Kiểm tra chữ số */
    | 'special'     /* Kiểm tra ký tự đặc biệt */
    | 'noWhitespace'/* Không có khoảng trắng */
    | 'email';      /* Kiểm tra định dạng email */

/****************************************************************************
* RegexInputType: Loại input                                                *
*****************************************************************************/
export type RegexInputType =
    'text'          /* Input dạng text */
    | 'password';   /* Input dạng password */

/****************************************************************************
* RegexInputProps: Thuộc tính cho component RegexInput                      *
*****************************************************************************/
export type RegexInputProps = TextInputProps & {
    /****************************************************************************
     * Placeholder cho input (tuỳ chọn)                                         *
     * @optional                                                                *
     ****************************************************************************/
    placeholder?: string;
    /****************************************************************************
     * Kiểu dáng cho input (tuỳ chọn)                                           *
     * @optional                                                                *
     ****************************************************************************/
    style?: StyleProp<TextStyle>;
    /****************************************************************************
     * Giá trị của input (tuỳ chọn)                                             *
     * @optional                                                                *
     ****************************************************************************/
    value?: string;
    /****************************************************************************
     * Hàm xử lý khi thay đổi text (tuỳ chọn)                                   *
     * @optional                                                                *
     ****************************************************************************/
    onChangeText?: (text: string) => void;
    /****************************************************************************
     * Danh sách các kiểm tra regex (tuỳ chọn)                                  *
     * @optional                                                                *
     ****************************************************************************/
    regexChecks?: RegexInputCheckType[];
    /****************************************************************************
     * Loại input (text/password, tuỳ chọn)                                     *
     * @optional                                                                *
     ****************************************************************************/
    inputType?: RegexInputType;
    /****************************************************************************
     * Tên của input (tuỳ chọn)                                                 *
     * @optional                                                                *
     ****************************************************************************/
    inputName?: string;
    /****************************************************************************
     * Thông báo lỗi (tuỳ chọn)                                                 *
     * @optional                                                                *
     ****************************************************************************/
    errorMessage?: string;
};