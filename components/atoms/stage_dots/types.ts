import { ViewStyle } from "react-native";

/****************************************************************************
* StageDotsProps: Thuộc tính cho component StageDots                        *
****************************************************************************/
export type StageDotsProps = {
    /****************************************************************************
     * Độ dài (width) cho từng dot (px)                                         *
     ****************************************************************************/
    lengths: number[];
    /****************************************************************************
     * Chiều cao cố định cho tất cả dot (tuỳ chọn)                              *
     * @optional                                                                *
     ****************************************************************************/
    height?: number;
    /****************************************************************************
     * Index của dot đang active                                                *
     ****************************************************************************/
    activeIndex: number;
    /****************************************************************************
     * Màu cho dot không active (tuỳ chọn)                                      *
     * @optional                                                                *
     ****************************************************************************/
    inactiveColor?: string;
    /****************************************************************************
     * Màu cho dot active (tuỳ chọn)                                            *
     * @optional                                                                *
     ****************************************************************************/
    activeColor?: string;
    /****************************************************************************
     * Độ rộng cộng thêm khi dot active (px, tuỳ chọn)                          *
     * @optional                                                                *
     ****************************************************************************/
    activeExtraWidth?: number;
    /****************************************************************************
     * Kiểu dáng cho container (tuỳ chọn)                                       *
     * @optional                                                                *
     ****************************************************************************/
    style?: ViewStyle;
};

/****************************************************************************
* DotProps: Thuộc tính cho từng dot                                         *
****************************************************************************/
export type DotProps = {
    /****************************************************************************
     * Độ dài (width) của dot                                                   *
     ****************************************************************************/
    length: number;
    /****************************************************************************
     * Chiều cao của dot                                                        *
     ****************************************************************************/
    height: number;
    /****************************************************************************
     * Trạng thái active                                                        *
     ****************************************************************************/
    isActive: boolean;
    /****************************************************************************
     * Màu cho dot không active                                                 *
     ****************************************************************************/
    inactiveColor: string;
    /****************************************************************************
     * Màu cho dot active                                                       *
     ****************************************************************************/
    activeColor: string;
    /****************************************************************************
     * Độ rộng cộng thêm khi dot active                                         *
     ****************************************************************************/
    activeExtraWidth: number;
};
