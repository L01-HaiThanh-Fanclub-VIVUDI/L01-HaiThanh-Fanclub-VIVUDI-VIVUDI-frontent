/****************************************************************************
* LoadingContextType: Giá trị context cho LoadingProvider                   *
* - Cung cấp các hàm show, hide và trạng thái isLoading.                    *
* - Được sử dụng để quản lý trạng thái loading toàn cục trong ứng dụng.     *
****************************************************************************/
export type LoadingContextType = {
    /****************************************************************************
     * Hiển thị loading                                                         *
     ****************************************************************************/
    show: () => void;
    /****************************************************************************
     * Ẩn loading                                                               *
     ****************************************************************************/
    hide: () => void;
    /****************************************************************************
     * Trạng thái loading hiện tại                                              *
     ****************************************************************************/
    isLoading: boolean;
};